import java.util.Properties

// The keystore file is only required to sign a release build. Loading it must not
// break configuration for every other task (assembleDebug, lint, IDE sync, ...).
val keystorePropertiesFile = rootProject.file("app/keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasReleaseKeystore = listOf("storeFile", "storePassword", "keyAlias", "keyPassword")
    .all { keystoreProperties.getProperty(it)?.isNotBlank() == true }

android {
    namespace = "com.timer.minimal"
